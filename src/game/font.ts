export const CHAR_W = 8
export const CHAR_H = 8

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
): void {
  ctx.fillStyle = color
  for (let i = 0; i < text.length; i++) {
    const g = GLYPHS[text[i].toUpperCase()]
    if (!g) continue
    for (let r = 0; r < 8; r++) {
      const bits = g[r]
      if (bits === 0) continue
      for (let c = 0; c < 8; c++) {
        if (bits & (0x80 >> c)) ctx.fillRect(x + i * CHAR_W + c, y + r, 1, 1)
      }
    }
  }
}

export function textWidth(text: string): number {
  return text.length * CHAR_W
}
