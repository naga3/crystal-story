function decode(width: number, height: number, packed: string): Cell[][] {
  const grid: Cell[][] = []
  let idx = 0
  for (let y = 0; y < height; y++) {
    const row: Cell[] = []
    for (let x = 0; x < width; x += 2) {
      const v = Number(packed[idx++])
      row.push(Math.floor(v / 3) as Cell)
      row.push((v % 3) as Cell)
    }
    grid.push(row)
  }
  return grid
}

